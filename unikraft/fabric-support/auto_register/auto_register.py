def render_fabric_init_h(fabric_names: list[str], fc_rel: str) -> str:
    lines = [
        "/* Auto-generated by auto_register.py — do not edit */",
        "#ifndef _FABRIC_INIT_H_",
        "#define _FABRIC_INIT_H_",
        "",
        f'#include "{fc_rel}/fabric/include/fabric.h"',
        "",
    ]
    for name in fabric_names:
        lines.append(f"extern Fabric *g_{c_safe(name)};")
    lines.extend(["", "int fabric_init_all(void);", "", "#endif", ""])
    return "\n".join(lines)


def render_fabric_init_c(
    fabric_names: list[str],
    fabric_libs: dict[str, list[str]],
    edges: list[tuple[str, str]],
    reg_plan: dict[str, list[str]],
    lib_fabric: dict[str, int],
    default_fabric: int,
    isolation_backend: str = "ept",
    fc_rel: str = "../fabric-core",
    default_fabrics: dict[str, str] | None = None,
    skip_page_tagging: bool = False,
    isolated_initcalls: list[dict[str, Any]] | None = None,
) -> str:
    lines = [
        "/* Auto-generated by auto_register.py — do not edit */",
        '#include "fabric_init.h"',
        '#include "fabric_register_all.h"',
        f'#include "{fc_rel}/backends/include/backends.h"',
        f'#include "{fc_rel}/bridge/include/bridge.h"',
        f'#include "{fc_rel}/component/include/component.h"',
        f'#include "{fc_rel}/controller/include/controller.h"',
        f'#include "{fc_rel}/include/fabric_error.h"',
        '#include <flexos/isolation.h>',
    ]
    if isolation_backend == "mpk":
        lines.append('#include <flexos/impl/intelpku.h>')
    elif isolation_backend == "ept":
        lines.append('#include <uk/config.h>')
        lines.append('#if CONFIG_LIBFLEXOS_VMEPT')
        lines.append('#include <flexos/impl/vmept.h>')
        lines.append('#endif')
    lines.extend([
        '#include <fabric/isolation.h>',
        '#include <stdio.h>',
        '#include <uk/init.h>',
        '#include <uk/page.h>',
        '#include <uk/prio.h>',
        "",
        "int fabric_bridge_bind_downstream(struct FabricBridge *bridge, Fabric *fabric);",
        "",
    ])

    # 全局 fabric 指针
    for name in fabric_names:
        lines.append(f"Fabric *g_{c_safe(name)} = (void *)0;")
    lines.extend(["", ""])

    # 双向桥接辅助函数
    lines.extend([
        "static int fabric_bind_bidi(Fabric *left, Fabric *right)",
        "{",
        "    if (!left || !right || !left->bridge || !right->bridge)",
        "        return FABRIC_ERROR;",
        "    if (fabric_bridge_bind_downstream(left->bridge, right) != FABRIC_SUCCESS)",
        "        return FABRIC_ERROR;",
        "    if (fabric_bridge_bind_downstream(right->bridge, left) != FABRIC_SUCCESS)",
        "        return FABRIC_ERROR;",
        "    return FABRIC_SUCCESS;",
        "}",
        "",
    ])

    # fabric_init_all()
    lines.extend([
        "int fabric_init_all(void)",
        "{",
        "    int rc;",
        "",
    ])

    # 创建 fabric
    for name in fabric_names:
        cname = c_safe(name)
        lines.append(f"    g_{cname} = fabric_create();")
    guard = " || ".join(f"!g_{c_safe(name)}" for name in fabric_names)
    lines.append(f"    if ({guard})")
    lines.append("        return FABRIC_ERROR;")
    lines.append("")

    # 注册函数
    lines.append("    struct fabric_lib_binding {")
    lines.append("        const char *lib_name;")
    lines.append("        Fabric *fabric;")
    lines.append("        int (*register_fn)(Fabric *);")
    lines.append("    };")
    lines.append("")
    lines.append("    struct fabric_lib_binding bindings[] = {")
    seen_bindings: set[tuple[str, str]] = set()
    for lib in sorted(reg_plan.keys()):
        fabric_idx = lib_fabric.get(lib, default_fabric)
        if fabric_idx < 0 or fabric_idx >= len(fabric_names):
            continue
        fabric_name = fabric_names[fabric_idx]
        key = (lib, fabric_name)
        if key in seen_bindings:
            continue
        seen_bindings.add(key)
        cname = c_safe(fabric_name)
        lines.append(f'        {{ "{lib}", g_{cname}, register_{lib}_functions }},')
    lines.append("    };")
    lines.append("    int binding_count = (int)(sizeof(bindings) / sizeof(bindings[0]));")
    lines.append("    for (int i = 0; i < binding_count; i++) {")
    lines.append("        rc = bindings[i].register_fn(bindings[i].fabric);")
    lines.append("        if (rc != FABRIC_SUCCESS)")
    lines.append("            return rc;")
    lines.append("    }")
    lines.append("")

    # 连接桥接边
    for left, right in edges:
        lines.append(f"    rc = fabric_bind_bidi(g_{c_safe(left)}, g_{c_safe(right)});")
        lines.append("    if (rc != FABRIC_SUCCESS)")
        lines.append("        return rc;")
    lines.append("")

    # 隔离后端初始化（在桥接绑定之后，确保 downstream 拓扑已就绪）
    iso_enum, iso_cfg_type = ISO_MAP.get(isolation_backend, ("", ""))
    if iso_enum:
        lines.append("    /* --- 隔离后端初始化 --- */")
        lines.append("    {")
        lines.append(f"        {iso_cfg_type} iso_cfg;")
        for name in fabric_names:
            cname = c_safe(name)
            lines.append(f"        iso_cfg.fabric_id = g_{cname}->fabric_id;")
            lines.append(f"        fabric_bridge_set_isolation(g_{cname}->bridge, {iso_enum}, &iso_cfg);")
        lines.append("    }")
        lines.append("")
    else:
        lines.append(f"    /* [warning] 未知的隔离后端: {isolation_backend}，跳过隔离初始化 */")
        lines.append("")

    # MPK 内存页面标记（非默认 fabric 的 section 打上 fabric key）
    default_names = set(default_fabrics.values()) if default_fabrics else set()
    iso_fabrics = [n for n in fabric_names if n not in default_names]
    if iso_fabrics and isolation_backend == "mpk" and not skip_page_tagging:
        lines.append("    /* --- MPK 内存页面标记 --- */")
        lines.append("    {")
        lines.append("        extern int flexos_intelpku_mem_set_key(void *, uint64_t, uint8_t);")
        for name in iso_fabrics:
            cname = c_safe(name)
            lines.append(f"        extern char _fabric_{cname}_data_start[], _fabric_{cname}_data_end[];")
            lines.append(f"        extern char _fabric_{cname}_bss_start[], _fabric_{cname}_bss_end[];")
            lines.append(f"        extern char _fabric_{cname}_text_start[], _fabric_{cname}_text_end[];")
        lines.append("")
        for name in iso_fabrics:
            cname = c_safe(name)
            lines.append(f"        /* tag {name} sections with fabric key */")
            lines.append(f"        do {{")
            # Do not printf here: after uksched pages get a non-zero key,
            # stdio locking may call uk_sched_get_default() and PF_PK on .bss.
            lines.append(f"            MPKBridgeState *_st = g_{cname}->bridge->iso_state ?")
            lines.append(f"                (MPKBridgeState *)g_{cname}->bridge->iso_state : (void *)0;")
            lines.append(f"            uint32_t _key = _st ? _st->my_key : 0;")
            lines.append(f"            if (_key > 0) {{")
            lines.append(f"                uintptr_t _s, _e, _np;")
            lines.append(f"                _s = (uintptr_t)_fabric_{cname}_data_start & ~(uintptr_t)0xFFF;")
            lines.append(f"                _e = ((uintptr_t)_fabric_{cname}_data_end + 0xFFF) & ~(uintptr_t)0xFFF;")
            lines.append(f"                _np = (_e > _s) ? (_e - _s) / __PAGE_SIZE : 0;")
            lines.append(f"                if (_np) flexos_intelpku_mem_set_key((void *)_s, _np, _key);")
            lines.append(f"                _s = (uintptr_t)_fabric_{cname}_bss_start & ~(uintptr_t)0xFFF;")
            lines.append(f"                _e = ((uintptr_t)_fabric_{cname}_bss_end + 0xFFF) & ~(uintptr_t)0xFFF;")
            lines.append(f"                _np = (_e > _s) ? (_e - _s) / __PAGE_SIZE : 0;")
            lines.append(f"                if (_np) flexos_intelpku_mem_set_key((void *)_s, _np, _key);")
            lines.append(f"                _s = (uintptr_t)_fabric_{cname}_text_start & ~(uintptr_t)0xFFF;")
            lines.append(f"                _e = ((uintptr_t)_fabric_{cname}_text_end + 0xFFF) & ~(uintptr_t)0xFFF;")
            lines.append(f"                _np = (_e > _s) ? (_e - _s) / __PAGE_SIZE : 0;")
            lines.append(f"                if (_np) flexos_intelpku_mem_set_key((void *)_s, _np, _key);")
            lines.append(f"            }}")
            lines.append(f"        }} while (0);")
        lines.append("    }")
        lines.append("")

    lines.extend([
        "    return FABRIC_SUCCESS;",
        "}",
        "",
    ])

    isolated_initcalls = isolated_initcalls or []
    for item in isolated_initcalls:
        lines.append(f"extern int {item['gate_sym']}(void);")
    if isolated_initcalls:
        lines.append("")
    for item in isolated_initcalls:
        lines.extend([
            f"/* Route {item['init_fn']} through fabric gate (lib in non-default fabric). */",
            f"static int {item['stub']}(void)",
            "{",
            "    int rc = 0;",
            "#if CONFIG_LIBFLEXOS_VMEPT",
            "    /* Library VMs must reach master_rpc_loop before any cross-comp",
            "     * gate. Only the app compartment drives isolated lib inits",
            "     * (after boot.c has created peer RPC threads). */",
            "    if (flexos_vmept_comp_id != FLEXOS_VMEPT_APPCOMP)",
            "        return 0;",
            "#endif",
            f"    fabric_gate_r({default_fabric}, rc, {item['gate_sym']});",
            "    return rc;",
            "}",
            f"uk_lib_initcall_prio({item['stub']}, UK_PRIO_LATEST);",
            "",
        ])

    lines.extend([
        "static int __fabric_lib_init(void)",
        "{",
        "    return fabric_init_all();",
        "}",
        "uk_lib_initcall_prio(__fabric_lib_init, UK_PRIO_EARLIEST);",
        "",
    ])
    return "\n".join(lines)


