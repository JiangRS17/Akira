def render_register_all_h(reg_plan: dict[str, list[str]], fc_rel: str) -> str:
    lines = [
        "/* Auto-generated by auto_register.py — do not edit */",
        "#ifndef _FABRIC_REGISTER_ALL_H_",
        "#define _FABRIC_REGISTER_ALL_H_",
        "",
        f'#include "{fc_rel}/include/fabric_error.h"',
        f'#include "{fc_rel}/fabric/include/fabric.h"',
        "",
        "typedef struct Fabric Fabric;",
        "typedef void (*func_t)(void);",
        "int fabric_register_function(Fabric *fabric, const char *func_name, func_t func_ptr);",
        "",
    ]
    for lib in reg_plan:
        lines.append(f"int register_{lib}_functions(Fabric *fabric);")
    lines.extend(["", "#endif", ""])
    return "\n".join(lines)


def render_register_all_c(reg_plan: dict[str, list[str]]) -> str:
    lines = [
        "/* Auto-generated by auto_register.py — do not edit */",
        '#include "fabric_register_all.h"',
        '#include <uk/print.h>',
        "",
    ]
    # Weak extern declarations
    for funcs in reg_plan.values():
        for func in funcs:
            lines.append(f'extern const char __fsym_{func}[] __asm__("{func}") __attribute__((weak));')
    lines.append("")

    for lib, funcs in reg_plan.items():
        lines.append(f"int register_{lib}_functions(Fabric *fabric)")
        lines.append("{")
        lines.append("    int rc;")
        lines.append("    int registered = 0;")
        lines.append("    int missing = 0;")
        for func in funcs:
            lines.append(f"    if (__fsym_{func} == (const char *)0) {{")
            lines.append(f'        uk_pr_info("[fabric-register] skip unresolved: {func} ({lib})\\n");')
            lines.append("        missing++;")
            lines.append("    } else {")
            lines.append(f'        rc = fabric_register_function(fabric, "{func}", (func_t)(void *)__fsym_{func});')
            lines.append("        if (rc != FABRIC_SUCCESS)")
            lines.append("            return rc;")
            lines.append("        registered++;")
            lines.append("    }")
        lines.append(
            f'    uk_pr_info("[fabric-register] {lib}: %d registered, %d missing, {len(funcs)} total\\n",'
            " registered, missing);"
        )
        lines.append("    return FABRIC_SUCCESS;")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


