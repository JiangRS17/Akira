def build_rewrite_plan(
    cross_calls: list[CallSite],
    lib_fabric: dict[str, int],
    default_fabric: int,
) -> dict[Path, dict[str, Any]]:
    """Map source file → {src_fabric: int, funcs: set[str]}."""
    by_file: dict[Path, dict[str, Any]] = {}
    for call in cross_calls:
        if not call.registerable:
            continue
        caller_fabric = lib_fabric.get(call.caller_lib, default_fabric)
        callee_fabric = lib_fabric.get(call.callee_lib, default_fabric)
        if caller_fabric == callee_fabric:
            continue
        data = by_file.setdefault(call.path, {"src_fabric": caller_fabric, "funcs": set()})
        data["funcs"].add(call.func)
    return by_file


def render_cocci_rules_for_file(src_fabric: int, funcs: list[str], label: str) -> str:
    """Generate Coccinelle rules for one source file."""
    lines = [f"// Auto-generated for {label}", ""]
    for idx, func in enumerate(funcs):
        lines.extend([
            f"@noreturn_{idx}@",
            "expression list EL;",
            "expression COMP_FROM, COMP_TO;",
            "@@",
            f"- flexos_nop_gate(COMP_FROM, COMP_TO, {func}, EL)",
            f"+ fabric_gate({src_fabric}, {func}, EL)",
            "",
            f"@return_{idx}@",
            "expression list EL;",
            "expression COMP_FROM, COMP_TO, RET;",
            "@@",
            f"- flexos_nop_gate_r(COMP_FROM, COMP_TO, RET, {func}, EL)",
            f"+ fabric_gate_r({src_fabric}, RET, {func}, EL)",
            "",
        ])
    return "\n".join(lines) + "\n"


def render_isolated_lwip_sync_init_cocci() -> str:
    # Match both nop and vmept gates (VMEPT builds rewrite nop→vmept first).
    return """// Force synchronous lwip_init when lwip runs in an isolated fabric
@lwip_sync_init_for_isolation@
@@
-	tcpip_init(_lwip_init_done, NULL);
-
-	/* Wait until stack is booted */
-	flexos_vmept_gate(0, 0, uk_semaphore_down, &_lwip_init_sem);
+	/* fabric-isolated: sync init (avoid cross-VM sem deadlock on VMEPT) */
+	lwip_init();

@lwip_sync_init_for_isolation_nop@
@@
-	tcpip_init(_lwip_init_done, NULL);
-
-	/* Wait until stack is booted */
-	flexos_nop_gate(0, 0, uk_semaphore_down, &_lwip_init_sem);
+	/* fabric-isolated: sync init */
+	lwip_init();
"""


def render_disable_initcall_cocci(init_fn: str) -> str:
  return f"""// Disable direct uk_lib_initcall for fabric-isolated library
@disable_{init_fn}@
@@
-uk_lib_initcall({init_fn});
+/* fabric-isolated: {init_fn} invoked via fabric gate */
"""


def write_rewrite_artifacts(
    out_dir: Path,
    rewrite_plan: dict[Path, dict[str, Any]],
    isolated_initcalls: list[dict[str, Any]] | None = None,
) -> None:
    """Write Coccinelle rules and apply script to out_dir."""
    cocci_dir = out_dir / "cocci"
    cocci_dir.mkdir(parents=True, exist_ok=True)

    # Remove stale rules
    for stale in cocci_dir.glob("rule_*.cocci"):
        stale.unlink()

    merged_lines = ["// Auto-generated by auto_register.py — do not edit", ""]

    script_lines = [
        "#!/bin/sh",
        "set -eu",
        "",
        "ensure_include() {",
        "    file=$1",
        "    if grep -q 'fabric/isolation.h' \"$file\" 2>/dev/null; then",
        "        return 0",
        "    fi",
        "    python3 - \"$file\" <<'PY'",
        "from pathlib import Path",
        "import sys",
        "path = Path(sys.argv[1])",
        "text = path.read_text(encoding='utf-8')",
        "needle = '#include <flexos/isolation.h>\\n'",
        "insert = '#include <flexos/isolation.h>\\n#include <fabric/isolation.h>\\n'",
        "if 'fabric/isolation.h' in text:",
        "    raise SystemExit(0)",
        "if needle in text:",
        "    text = text.replace(needle, insert, 1)",
        "else:",
        "    text = '#include <fabric/isolation.h>\\n' + text",
        "path.write_text(text, encoding='utf-8')",
        "PY",
        "}",
        "",
    ]

    if not rewrite_plan and not isolated_initcalls:
        script_lines.append("echo '[fabric] no cross-fabric rewrites required'")

    rule_idx = 0
    for path, data in sorted(rewrite_plan.items(), key=lambda item: str(item[0])):
        funcs = sorted(data["funcs"])
        cocci_path = cocci_dir / f"rule_{rule_idx}.cocci"
        contents = render_cocci_rules_for_file(data["src_fabric"], funcs, str(path))
        cocci_path.write_text(contents, encoding="utf-8")
        merged_lines.append(contents.rstrip())
        merged_lines.append("")
        script_lines.append(f"spatch --sp-file '{cocci_path}' '{path}' --in-place")
        script_lines.append(f"ensure_include '{path}'")
        rule_idx += 1

    for item in isolated_initcalls or []:
        cocci_path = cocci_dir / f"rule_{rule_idx}.cocci"
        contents = render_disable_initcall_cocci(item["init_fn"])
        cocci_path.write_text(contents, encoding="utf-8")
        merged_lines.append(contents.rstrip())
        merged_lines.append("")
        script_lines.append(
            f"spatch --sp-file '{cocci_path}' '{item['source']}' --in-place || true"
        )
        rule_idx += 1

    # Intentionally skip sync-init cocci: tcpip_init is required for Redis
    # Socket API (NO_SYS=0). It works when MPK section tagging is skipped.
    lwip_items = []
    if False and lwip_items:
        pass

    (out_dir / "fabric_gates_rules.cocci").write_text(
        "\n".join(merged_lines).rstrip() + "\n", encoding="utf-8"
    )
    apply_script = out_dir / "apply_fabric_rules.sh"
    apply_script.write_text("\n".join(script_lines) + "\n", encoding="utf-8")
    apply_script.chmod(0o755)


# ===================================================================
#  主入口 — 统一生成所有产物
# ===================================================================

def main() -> int:
    parser = argparse.ArgumentParser(
        description="Fabric code generator — produces registration, init, and Coccinelle artifacts."
    )
    parser.add_argument("--app-dir", type=Path, required=True,
                        help="Application directory containing fabric.yaml and kraft.yaml")
    parser.add_argument("--out-dir", type=Path, required=True,
                        help="Output directory for generated files")
    parser.add_argument("--lib-root", type=Path, required=True,
                        help="Root directory of unikraft libs (e.g. unikraft/lib)")
    parser.add_argument("--ext-lib-root", type=Path, default=None,
                        help="Root directory of external libs (e.g. libs/)")
    parser.add_argument("--skip-page-tagging", action="store_true",
                        help="Skip MPK page tagging code generation (for pre-injection build)")
    args = parser.parse_args()

    # ------------------------------------------------------------------
    # 1. 统一分析
    # ------------------------------------------------------------------
    try:
        result = analyze(args.app_dir, args.lib_root, args.ext_lib_root)
    except FileNotFoundError as e:
        print(f"[error] {e}", file=sys.stderr)
        return 1

    print(f"[info] app library name : {result.app_lib_name}")
    print(f"[info] app runtime lib  : {result.app_runtime_lib}")
    print(f"[info] default compartment: {result.default_compartment}")
    print(f"[info] isolation backend: {result.isolation_backend}")
    print(f"[info] fabrics ({len(result.fabric_names)}):")
    for i, name in enumerate(result.fabric_names):
        libs = result.fabric_libs.get(name, [])
        print(f"  [{i}] {name}: {', '.join(libs) or '(empty)'}")
    print(f"[info] bridge edges ({len(result.edges)}):")
    for left, right in result.edges:
        print(f"  {left} <-> {right}")
    print(f"[info] function index: {len(result.function_index)} entries")
    print(f"[info] export index  : {len(result.export_index)} entries")
    print(f"[info] nop_gate call sites  : {len(result.call_sites)}")
    print(f"[info] cross-fabric calls   : {len(result.cross_calls)}")

    # ------------------------------------------------------------------
    # 2. 计算相对路径
    # ------------------------------------------------------------------
    out_dir = args.out_dir.resolve()
    fc_rel = fabric_core_rel(out_dir, args.lib_root.resolve())
    print(f"[info] fabric-core relative path: {fc_rel}")

    args.out_dir.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------------
    # 3. 生成注册文件
    # ------------------------------------------------------------------
    reg_plan = dict(result.reg_plan)
    isolated_initcalls = find_isolated_lib_initcalls(
        result.fabric_libs, result.default_fabrics, args.ext_lib_root,
        result.lib_fabric, result.fabric_names,
    )
    for item in isolated_initcalls:
        print(
            f"[info] isolated initcall: {item['init_fn']} -> "
            f"fabric_gate({item['fabric_idx']}, {item['gate_sym']})"
        )

    for fname, libs in result.fabric_libs.items():
        if fname in set(result.default_fabrics.values()):
            continue
        if "lwip" in libs:
            funcs = set(reg_plan.get("lwip", []))
            funcs.add("_liblwip_init")
            reg_plan["lwip"] = sorted(funcs)
            break

    (args.out_dir / "fabric_register_all.h").write_text(
        render_register_all_h(reg_plan, fc_rel), encoding="utf-8"
    )
    (args.out_dir / "register_all.c").write_text(
        render_register_all_c(reg_plan), encoding="utf-8"
    )

    # ------------------------------------------------------------------
    # 4. 生成初始化文件
    # ------------------------------------------------------------------
    (args.out_dir / "fabric_init.h").write_text(
        render_fabric_init_h(result.fabric_names, fc_rel), encoding="utf-8"
    )
    (args.out_dir / "fabric_init.c").write_text(
        render_fabric_init_c(
            result.fabric_names, result.fabric_libs, result.edges,
            reg_plan, result.lib_fabric, result.default_fabric,
            result.isolation_backend, fc_rel,
            default_fabrics=result.default_fabrics,
            skip_page_tagging=args.skip_page_tagging,
            isolated_initcalls=isolated_initcalls,
        ),
        encoding="utf-8",
    )

    # ------------------------------------------------------------------
    # 5. 生成 per-library linker script（用于 partial link 阶段重命名 section）
    # ------------------------------------------------------------------
    default_fabric_names = set(result.default_fabrics.values())
    lib_ld_count = 0
    for fname, libs in result.fabric_libs.items():
        if fname in default_fabric_names or not libs:
            continue
        safe = c_safe(fname)
        for lib in libs:
            # per-library partial link 阶段只有一个库的 .o 文件，
            # 用 * 通配符匹配即可（不会有其他库的对象混入）
            ld_content = "\n".join([
                "SECTIONS {",
                f"    .data_{safe} : {{",
                f"        *(.data .data.* .rodata .rodata.* .sdata .sdata.*)",
                f"    }}",
                f"    .bss_{safe} : {{",
                f"        *(.bss .bss.* .sbss .sbss.* COMMON)",
                f"    }}",
                f"    .text_{safe} : {{",
                f"        *(.text .text.*)",
                f"    }}",
                "}",
                "",
            ])
            ld_path = args.out_dir / f"lib_{lib}_fabric.ld"
            ld_path.write_text(ld_content, encoding="utf-8")
            lib_ld_count += 1
    print(f"[info] per-library linker scripts: {lib_ld_count}")

    # ------------------------------------------------------------------
    # 6. 生成 Coccinelle 重写规则
    # ------------------------------------------------------------------
    rewrite_plan = build_rewrite_plan(
        result.cross_calls, result.lib_fabric, result.default_fabric
    )
    write_rewrite_artifacts(args.out_dir, rewrite_plan, isolated_initcalls)

    # ------------------------------------------------------------------
    # 输出摘要
    # ------------------------------------------------------------------
    total_funcs = sum(len(v) for v in reg_plan.values())
    print(f"[info] registered functions: {total_funcs}")
    for lib, funcs in sorted(reg_plan.items()):
        print(f"  [register] {lib}: {', '.join(funcs)}")
    skipped = sorted({c.func for c in result.cross_calls if not c.registerable})
    for func in skipped:
        print(f"  [direct] {func}")
    print(f"[info] rewrite plan: {len(rewrite_plan)} file(s)")
    for path, data in sorted(rewrite_plan.items(), key=lambda x: str(x[0])):
        print(f"  [rewrite] {path} ({len(data['funcs'])} funcs)")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
