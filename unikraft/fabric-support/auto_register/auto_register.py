#!/usr/bin/env python3
"""Fabric code generator — single entry point for all generated artifacts.

Reads ``fabric.yaml`` + ``kraft.yaml`` via ``parse_config.analyze()``, then
generates:

- ``fabric_register_all.h`` / ``register_all.c`` — per-library registration
- ``fabric_init.h`` / ``fabric_init.c`` — fabric creation, isolation init,
  bridge wiring, function registration
- Coccinelle ``.cocci`` rules + ``apply_fabric_rules.sh`` — rewrite
  ``flexos_nop_gate`` → ``fabric_gate`` in source files
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

# Add parse_config directory to path so we can import its functions
_parse_config_dir = str(Path(__file__).resolve().parent.parent / "parse_config")
if _parse_config_dir not in sys.path:
    sys.path.insert(0, _parse_config_dir)

from parse_config import (
    AnalysisResult,
    CallSite,
    ISO_MAP,
    analyze,
    c_safe,
    fabric_core_rel,
    normalise_lib_name,
)

# Libraries with uk_lib_initcall entry points that must not run directly
# when placed in a non-default fabric (MPK would fault on direct call).
ISOLATED_LIB_INITCALLS: dict[str, dict[str, Any]] = {
    "lwip": {
        "init_fn": "liblwip_init",
        "gate_sym": "_liblwip_init",
        "init_source": ("lwip", "init.c"),
    },
}


def find_isolated_lib_initcalls(
    fabric_libs: dict[str, list[str]],
    default_fabrics: dict[str, str] | None,
    ext_lib_root: Path | None,
    lib_fabric: dict[str, int] | None = None,
    fabric_names: list[str] | None = None,
) -> list[dict[str, Any]]:
    """Return isolated libs whose initcall must be routed through fabric_gate."""
    default_names = set(default_fabrics.values()) if default_fabrics else set()
    fabric_index = {name: idx for idx, name in enumerate(fabric_names or [])}
    found: list[dict[str, Any]] = []
    if ext_lib_root is None:
        return found

    for fname, libs in fabric_libs.items():
        if fname in default_names:
            continue
        for lib in libs:
            meta = ISOLATED_LIB_INITCALLS.get(lib)
            if meta is None:
                continue
            rel_lib, rel_file = meta["init_source"]
            source = ext_lib_root / rel_lib / rel_file
            if not source.exists():
                continue
            fabric_idx = None
            if lib_fabric and lib in lib_fabric:
                fabric_idx = lib_fabric[lib]
            elif fname in fabric_index:
                fabric_idx = fabric_index[fname]
            if fabric_idx is None:
                continue
            found.append({
                "lib": lib,
                "init_fn": meta["init_fn"],
                "gate_sym": meta["gate_sym"],
                "fabric_idx": fabric_idx,
                "source": source.resolve(),
                "stub": f"__fabric_isolated_{normalise_lib_name(lib)}_init",
            })
    return found


